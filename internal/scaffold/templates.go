func mainGo(cfg Config) string {
	replyType := ""
	if cfg.trigger.usesReplyType {
		replyType = "\ntype ticketReply struct {\n\tStatus string `json:\"status\"`\n}\n"
	}
	return fmt.Sprintf(`package main

import (
	"log"
	"os"

	ovr %q
)
%s
func listenAddr() string {
	if addr := os.Getenv("OUVRIER_ADDR"); addr != "" {
		return addr
	}
	return ":8080"
}

func main() {
	if err := ovr.Run(listenAddr(),
		ovr.From(%s),
		ovr.Pipe("Handle the event and return a concise status.",
			ovr.Model(%q),
		),
		%s,
	); err != nil {
		log.Fatal(err)
	}
}
`, cfg.FrameworkModule, replyType, cfg.trigger.fromArg, cfg.Model, cfg.trigger.terminalExpr)
}

func goMod(cfg Config) string {
	body := fmt.Sprintf(`module %s

go 1.25.0

require %s v0.0.0
`, cfg.Name, cfg.FrameworkModule)
	if requirements := frameworkRequireBlocks(cfg); requirements != "" {
		body += "\n" + requirements
	}
	if cfg.FrameworkDir != "" {
		body += fmt.Sprintf(`
replace %s => %s
`, cfg.FrameworkModule, cfg.FrameworkDir)
	}
	return body
}

func frameworkRequireBlocks(cfg Config) string {
	if cfg.FrameworkDir == "" {
		return ""
	}
	data, err := os.ReadFile(filepath.Join(cfg.FrameworkDir, "go.mod"))
	if err != nil {
		return ""
	}

	var blocks []string
	lines := strings.Split(string(data), "\n")
	for i := 0; i < len(lines); i++ {
		line := strings.TrimSpace(lines[i])
		switch {
		case strings.HasPrefix(line, "require ("):
			var block []string
			for ; i < len(lines); i++ {
				block = append(block, lines[i])
				if strings.TrimSpace(lines[i]) == ")" {
					break
				}
			}
			blocks = append(blocks, strings.Join(block, "\n"))
		case strings.HasPrefix(line, "require "):
			blocks = append(blocks, lines[i])
		}
	}
	return strings.Join(blocks, "\n\n")
}

