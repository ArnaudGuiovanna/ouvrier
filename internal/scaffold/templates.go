func envYAML(cfg Config) string {
	env := requiredEnvVars(cfg)
	if len(env) == 0 {
		return "  required: []"
	}
	var b strings.Builder
	b.WriteString("  required:\n")
	for _, key := range env {
		b.WriteString("    - ")
		b.WriteString(key)
		b.WriteByte('\n')
	}
	return strings.TrimRight(b.String(), "\n")
}

type workerManifest struct {
	Name        string   `json:"name"`
	Description string   `json:"description"`
	Events      []string `json:"events"`
	Outcomes    []string `json:"outcomes"`
	AdminURL    string   `json:"admin_url"`
}

func workerManifestJSON(cfg Config) string {
	manifest := workerManifest{
		Name:        cfg.Name,
		Description: "Ouvrier worker generated by ouvrier new.",
		Events:      []string{workerManifestEvent(cfg)},
		Outcomes:    []string{workerManifestOutcome(cfg)},
		AdminURL:    "http://127.0.0.1:8080",
	}
	encoded, err := json.MarshalIndent(manifest, "", "  ")
	if err != nil {
		return "{}\n"
	}
	return string(encoded) + "\n"
}

func workerManifestEvent(cfg Config) string {
	switch cfg.trigger.kind {
	case triggerHTTP:
		return "http." + cfg.Trigger
	case triggerCron:
		return cfg.Trigger
	case triggerWebhook:
		return cfg.Trigger
	case triggerStream:
		return cfg.Trigger
	default:
		return cfg.Trigger
	}
}

func workerManifestOutcome(cfg Config) string {
	switch cfg.trigger.kind {
	case triggerHTTP:
		return "json_reply"
	default:
		return "log_sink"
	}
}

func envExample(cfg Config) string {
	var b strings.Builder
	for _, key := range envExampleVars(cfg) {
		b.WriteString(key)
		b.WriteString("=\n")
	}
	b.WriteString("OUVRIER_ENV=dev\n")
	b.WriteString("OUVRIER_ADDR=:8080\n")
	b.WriteString("OUVRIER_LOG_LEVEL=info\n")
	b.WriteString("OUVRIER_ADMIN_TOKEN=\n")
	return b.String()
}

func requiredEnvVars(cfg Config) []string {
	switch modelProvider(cfg.Model) {
	case "anthropic":
		return []string{"ANTHROPIC_API_KEY"}
	case "openai":
		return []string{"OPENAI_API_KEY"}
	case "mistral":
		return []string{"MISTRAL_API_KEY"}
	case "gemini":
		return []string{"GEMINI_API_KEY"}
	case "groq":
		return []string{"GROQ_API_KEY"}
	case "deepseek":
		return []string{"DEEPSEEK_API_KEY"}
	case "azure":
		return []string{"AZURE_OPENAI_API_KEY", "AZURE_OPENAI_BASE_URL"}
	case "bedrock":
		return []string{"AWS_ACCESS_KEY_ID", "AWS_SECRET_ACCESS_KEY", "AWS_REGION"}
	default:
		return nil
	}
}

func envExampleVars(cfg Config) []string {
	switch modelProvider(cfg.Model) {
	case "ollama":
		return []string{"OLLAMA_BASE_URL"}
	case "vllm":
		return []string{"VLLM_BASE_URL", "VLLM_API_KEY"}
	default:
		return requiredEnvVars(cfg)
	}
}

func modelProvider(model string) string {
	provider, _, _ := strings.Cut(strings.TrimSpace(model), "/")
	return strings.ToLower(provider)
}

func gitignore() string {
	// .env* covers per-environment files like .env.staging and .env.prod;
	// the committed .env.example template is explicitly re-included.
	return `.env*
!.env.example
bin/
dist/
*.log
`
}

